import React, { useEffect, useState } from 'react';
import { Activity, AlertTriangle, BarChart3, Database, RefreshCw, Waves } from 'lucide-react';

type SparkRow = Record<string, string | number | null>;

interface SparkAnalyticsResponse {
  source: string;
  available: boolean;
  generatedAt: string | null;
  message: string | null;
  summaries: Record<string, SparkRow[]>;
}

const analysisOptions = [
  { key: 'villageAverageWaterLevel', en: 'Village water levels', ta: 'ஊராட்சி நீர்மட்டம்' },
  { key: 'villageAverageFlow', en: 'Inlet and outlet flow', ta: 'உள்வரத்து மற்றும் வெளியேற்ற ஓட்டம்' },
  { key: 'tankWaterUsage', en: 'Tank water usage', ta: 'தொட்டி நீர் பயன்பாடு' },
  { key: 'leakageRiskRecords', en: 'Leakage risk records', ta: 'கசிவு அபாயப் பதிவுகள்' },
  { key: 'abnormalSensorReadings', en: 'Abnormal sensor readings', ta: 'அசாதாரண சென்சார் அளவீடுகள்' },
  { key: 'pumpStatusSummary', en: 'Pump status', ta: 'மோட்டார் நிலை' },
  { key: 'villageWaterWastage', en: 'Water wastage', ta: 'நீர் வீணாக்கம்' },
  { key: 'villageComplaintSummary', en: 'Village complaints', ta: 'ஊராட்சி புகார்கள்' },
  { key: 'overallWaterSupplySummary', en: 'Overall supply summary', ta: 'மொத்த நீர் விநியோகச் சுருக்கம்' }
] as const;

const formatColumnName = (name: string) => name.replace(/_/g, ' ');
const formatNumber = (value: string | number | null | undefined) =>
  typeof value === 'number' ? new Intl.NumberFormat().format(value) : value ?? '—';

export const SparkAnalyticsView: React.FC<{ tamilEnabled: boolean }> = ({ tamilEnabled }) => {
  const [result, setResult] = useState<SparkAnalyticsResponse | null>(null);
  const [selectedAnalysis, setSelectedAnalysis] = useState<string>('overallWaterSupplySummary');
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const loadResults = async () => {
    setLoading(true);
    setError(null);
    try {
      const response = await fetch(`${import.meta.env.BASE_URL}spark-analytics.json`);
      if (!response.ok) throw new Error(`Spark API returned ${response.status}`);
      setResult(await response.json() as SparkAnalyticsResponse);
    } catch (loadError) {
      setError(loadError instanceof Error ? loadError.message : 'Could not load Spark analytics.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    void loadResults();
  }, []);

  const overall = result?.summaries?.overallWaterSupplySummary?.[0];
  const selectedOption = analysisOptions.find(option => option.key === selectedAnalysis) ?? analysisOptions[0];
  const rows = result?.summaries?.[selectedAnalysis] ?? [];
  const columns = rows.length ? Object.keys(rows[0]) : [];

  const summaryCards = [
    {
      label: tamilEnabled ? 'பதிவுகள்' : 'Records',
      value: overall?.Unique_Record_Count,
      icon: Database,
      tint: 'text-cyan-800 bg-cyan-50'
    },
    {
      label: tamilEnabled ? 'ஊராட்சிகள்' : 'Villages',
      value: overall?.Village_Count,
      icon: Activity,
      tint: 'text-emerald-800 bg-emerald-50'
    },
    {
      label: tamilEnabled ? 'விநியோகம் (லிட்டர்)' : 'Supplied (litres)',
      value: overall?.Total_Supplied_Liters,
      icon: Waves,
      tint: 'text-blue-800 bg-blue-50'
    },
    {
      label: tamilEnabled ? 'கசிவு அபாயம் (%)' : 'Avg. leak risk (%)',
      value: overall?.Average_Leakage_Risk_Percentage,
      icon: AlertTriangle,
      tint: 'text-amber-800 bg-amber-50'
    }
  ];

  return (
    <section className="space-y-5 pb-12">
      <header className="flex flex-col gap-4 rounded-xl border border-slate-200 bg-white p-5 shadow-xs sm:flex-row sm:items-center sm:justify-between">
        <div>
          <div className="mb-1 flex items-center gap-2 text-xs font-bold uppercase text-cyan-800">
            <BarChart3 className="h-4 w-4" />
            <span>{tamilEnabled ? 'Scala DataFrame • Apache Spark SQL' : 'Scala DataFrame • Apache Spark SQL'}</span>
          </div>
          <h1 className="text-xl font-black text-slate-900 sm:text-2xl">
            {tamilEnabled ? 'Spark நீர் வலையமைப்பு பகுப்பாய்வு' : 'Spark Water Network Analytics'}
          </h1>
          <p className="mt-1 text-xs text-slate-600">
            {tamilEnabled
              ? 'Scala Spark job உருவாக்கிய உண்மையான சுருக்கத் தரவுகள்.'
              : 'Actual summary results generated by the Scala Spark batch job.'}
          </p>
        </div>
        <div className="flex items-center gap-3">
          <span className={`rounded-full px-3 py-1.5 text-[11px] font-bold ${result?.available ? 'bg-emerald-50 text-emerald-800' : 'bg-amber-50 text-amber-800'}`}>
            {loading
              ? (tamilEnabled ? 'ஏற்றப்படுகிறது' : 'Loading')
              : result?.available
                ? (tamilEnabled ? 'Spark முடிவுகள் இணைக்கப்பட்டன' : 'Spark results connected')
                : (tamilEnabled ? 'Spark வெளியீட்டுக்காக காத்திருக்கிறது' : 'Waiting for Spark output')}
          </span>
          <button
            type="button"
            onClick={() => void loadResults()}
            disabled={loading}
            title={tamilEnabled ? 'முடிவுகளைப் புதுப்பிக்கவும்' : 'Refresh results'}
            className="flex h-9 w-9 items-center justify-center rounded-lg border border-slate-300 bg-white text-slate-700 transition-colors hover:bg-slate-50 disabled:opacity-50"
          >
            <RefreshCw className={`h-4 w-4 ${loading ? 'animate-spin' : ''}`} />
          </button>
        </div>
      </header>

      {error && (
        <div role="alert" className="rounded-xl border border-rose-200 bg-rose-50 px-4 py-3 text-sm text-rose-800">
          {tamilEnabled ? 'Spark API-யிலிருந்து தரவைப் பெற முடியவில்லை.' : 'Could not load data from the Spark API.'} {error}
        </div>
      )}

      {result?.available && (
        <>
          <div className="grid grid-cols-2 gap-3 xl:grid-cols-4">
            {summaryCards.map(card => {
              const Icon = card.icon;
              return (
                <article key={card.label} className="rounded-xl border border-slate-200 bg-white p-4 shadow-xs">
                  <div className="flex items-center justify-between gap-2">
                    <span className="text-xs font-semibold text-slate-600">{card.label}</span>
                    <span className={`flex h-8 w-8 items-center justify-center rounded-lg ${card.tint}`}>
                      <Icon className="h-4 w-4" />
                    </span>
                  </div>
                  <div className="mt-3 text-xl font-black text-slate-950">
                    {formatNumber(card.value)}
                  </div>
                </article>
              );
            })}
          </div>

          {result.generatedAt && (
            <p className="text-right text-[11px] text-slate-500">
              {tamilEnabled ? 'கடைசி Spark செயலாக்கம்:' : 'Latest Spark output:'} {new Date(result.generatedAt).toLocaleString()}
            </p>
          )}

          <div className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-xs">
            <nav aria-label={tamilEnabled ? 'Spark பகுப்பாய்வுகள்' : 'Spark analyses'} className="flex gap-1 overflow-x-auto border-b border-slate-200 p-2">
              {analysisOptions.map(option => (
                <button
                  key={option.key}
                  type="button"
                  onClick={() => setSelectedAnalysis(option.key)}
                  className={`shrink-0 rounded-lg px-3 py-2 text-xs font-bold transition-colors ${selectedAnalysis === option.key ? 'bg-cyan-800 text-white' : 'text-slate-600 hover:bg-slate-100'}`}
                >
                  {tamilEnabled ? option.ta : option.en}
                  <span className={`ml-2 text-[10px] ${selectedAnalysis === option.key ? 'text-cyan-100' : 'text-slate-400'}`}>
                    {result.summaries[option.key]?.length ?? 0}
                  </span>
                </button>
              ))}
            </nav>

            <div className="flex items-center justify-between gap-3 px-4 py-3">
              <h2 className="text-sm font-extrabold text-slate-900">
                {tamilEnabled ? selectedOption.ta : selectedOption.en}
              </h2>
              <span className="text-[11px] text-slate-500">
                {rows.length} {tamilEnabled ? 'வரிசைகள்' : 'rows'}
              </span>
            </div>

            {rows.length ? (
              <div className="max-h-[60vh] overflow-auto border-t border-slate-100">
                <table className="min-w-full border-collapse text-left text-xs">
                  <thead className="sticky top-0 bg-slate-50 text-[10px] uppercase text-slate-600">
                    <tr>
                      {columns.map(column => (
                        <th key={column} className="whitespace-nowrap border-b border-slate-200 px-4 py-3 font-bold">
                          {formatColumnName(column)}
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100">
                    {rows.map((row, rowIndex) => (
                      <tr key={`${String(row.Record_ID ?? rowIndex)}-${rowIndex}`} className="hover:bg-cyan-50/40">
                        {columns.map(column => (
                          <td key={column} className="whitespace-nowrap px-4 py-3 text-slate-700">
                            {formatNumber(row[column])}
                          </td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            ) : (
              <div className="border-t border-slate-100 px-4 py-8 text-center text-sm text-slate-500">
                {tamilEnabled ? 'இந்தப் பகுப்பாய்வில் தரவு இல்லை.' : 'No records in this analysis.'}
              </div>
            )}
          </div>
        </>
      )}

      {!loading && !error && !result?.available && (
        <div className="rounded-xl border border-amber-200 bg-amber-50 p-5 text-sm text-amber-950">
          <h2 className="font-extrabold">
            {tamilEnabled ? 'இன்னும் Spark முடிவுகள் உருவாக்கப்படவில்லை' : 'Spark results have not been generated yet'}
          </h2>
          <p className="mt-1 text-xs leading-relaxed text-amber-900">
            {tamilEnabled
              ? 'உங்கள் உண்மையான CSV தரவுடன் Scala Spark job-ஐ இயக்கவும். JSON மற்றும் CSV சுருக்கங்கள் output/api மற்றும் output கோப்புறைகளில் உருவாகும்.'
              : 'Run the Scala Spark job with your real CSV dataset. It writes JSON summaries to output/api and CSV review files to output.'}
          </p>
          <code className="mt-3 block overflow-x-auto rounded-lg bg-amber-950 px-3 py-2 text-[11px] text-amber-50">
            spark-submit --class WaterAnalysis --master local[*] target/scala-2.12/jalmitra-water-analysis_2.12-0.1.0.jar data/water_network.csv output
          </code>
          <p className="mt-2 text-[11px] text-amber-900">
            {tamilEnabled ? 'பின்னர் இப்பக்கத்தில் புதுப்பிப்பு பொத்தானை அழுத்தவும்.' : 'Then press the refresh button on this page.'}
          </p>
        </div>
      )}
    </section>
  );
};
